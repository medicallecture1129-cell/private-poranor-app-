import { jsPDF } from 'jspdf';
import { Exam, ExamSubmission, LeaderboardRow } from '../types';

export const exportLeaderboardPDF = (
  examTitle: string,
  courseName: string,
  rows: LeaderboardRow[]
) => {
  const doc = new jsPDF('p', 'mm', 'a4');
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header Title
  doc.setFillColor(15, 23, 42); // Slate 900
  doc.rect(0, 0, pageWidth, 28, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('EXAM PORTAL', 14, 12);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Official Leaderboard | Course: ${courseName}`, 14, 18);
  doc.text(`Exam: ${examTitle}`, 14, 24);

  // Note: Per user specifications, 'Date & Time' is explicitly excluded from this leaderboard PDF
  let y = 36;

  // Table Header
  doc.setFillColor(241, 245, 249); // Slate 100
  doc.rect(14, y, pageWidth - 28, 9, 'F');
  doc.setDrawColor(203, 213, 225);
  doc.rect(14, y, pageWidth - 28, 9, 'S');

  doc.setTextColor(30, 41, 59);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');

  doc.text('Rank', 18, y + 6);
  doc.text('Student Name', 35, y + 6);
  doc.text('College', 90, y + 6);
  doc.text('Marks', 135, y + 6);
  doc.text('Percentage', 155, y + 6);
  doc.text('Duration', 180, y + 6);

  y += 9;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);

  rows.forEach((row) => {
    if (y > 275) {
      doc.addPage();
      y = 20;

      // Repeat Table Header
      doc.setFillColor(241, 245, 249);
      doc.rect(14, y, pageWidth - 28, 9, 'F');
      doc.setDrawColor(203, 213, 225);
      doc.rect(14, y, pageWidth - 28, 9, 'S');
      doc.setTextColor(30, 41, 59);
      doc.setFont('helvetica', 'bold');
      doc.text('Rank', 18, y + 6);
      doc.text('Student Name', 35, y + 6);
      doc.text('College', 90, y + 6);
      doc.text('Marks', 135, y + 6);
      doc.text('Percentage', 155, y + 6);
      doc.text('Duration', 180, y + 6);
      y += 9;
      doc.setFont('helvetica', 'normal');
    }

    // Row alternating background
    if (row.rank % 2 === 0) {
      doc.setFillColor(248, 250, 252);
      doc.rect(14, y, pageWidth - 28, 8, 'F');
    }
    doc.setDrawColor(226, 232, 240);
    doc.line(14, y + 8, pageWidth - 14, y + 8);

    doc.setTextColor(15, 23, 42);
    doc.text(`#${row.rank}`, 18, y + 5.5);
    doc.text(doc.splitTextToSize(row.studentName, 50)[0] || '', 35, y + 5.5);
    doc.text(doc.splitTextToSize(row.studentCollege, 42)[0] || '', 90, y + 5.5);
    doc.text(`${row.marksObtained}`, 135, y + 5.5);
    doc.text(`${row.percentage.toFixed(1)}%`, 155, y + 5.5);
    doc.text(row.durationFormatted, 180, y + 5.5);

    y += 8;
  });

  // Footer
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`Page ${i} of ${totalPages} - Generated by Exam Portal`, pageWidth / 2, 290, { align: 'center' });
  }

  doc.save(`${examTitle.replace(/[^a-zA-Z0-9]/g, '_')}_Leaderboard.pdf`);
};

export const exportAnswerScriptPDF = (
  exam: Exam,
  submission: ExamSubmission,
  studentName: string,
  college: string
) => {
  const doc = new jsPDF('p', 'mm', 'a4');
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header Title
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, pageWidth, 34, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('EXAM PORTAL - ANSWER SCRIPT', 14, 12);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Student: ${studentName} (${college})`, 14, 18);
  doc.text(`Exam: ${exam.title} | Course: ${exam.courseName}`, 14, 24);
  doc.text(
    `Marks: ${submission.marksObtained}/${exam.totalMarks} (${submission.percentage.toFixed(1)}%) | Correct: ${submission.correctCount} | Wrong: ${submission.wrongCount} | Skipped: ${submission.skippedCount}`,
    14,
    30
  );

  let y = 42;

  exam.questions.forEach((q, idx) => {
    const studentAns = submission.answers.find(a => a.questionId === q.id);
    const selected = studentAns?.selectedOption || 'Skipped';
    const isCorrect = studentAns?.isCorrect;
    const isSkipped = !studentAns || studentAns.selectedOption === null;

    if (y > 250) {
      doc.addPage();
      y = 20;
    }

    doc.setFillColor(isCorrect ? 240 : isSkipped ? 248 : 254, isCorrect ? 253 : isSkipped ? 250 : 242, isCorrect ? 244 : isSkipped ? 252 : 242);
    doc.setDrawColor(isCorrect ? 34 : isSkipped ? 148 : 239, isCorrect ? 197 : isSkipped ? 163 : 68, isCorrect ? 94 : isSkipped ? 184 : 68);
    doc.rect(14, y, pageWidth - 28, 7, 'F');

    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(15, 23, 42);
    doc.text(`Q${idx + 1}. ${q.text}`, 18, y + 5);

    y += 9;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);

    // Options
    q.options.forEach(opt => {
      let markBadge = '';
      if (opt.id === q.correctOption) markBadge += ' [Correct]';
      if (opt.id === selected) markBadge += ' [Your Choice]';

      doc.setTextColor(opt.id === q.correctOption ? 22 : opt.id === selected ? 220 : 71, opt.id === q.correctOption ? 101 : opt.id === selected ? 38 : 85, opt.id === q.correctOption ? 52 : opt.id === selected ? 38 : 105);
      doc.text(`${opt.id}) ${opt.text}${markBadge}`, 22, y);
      y += 5;
    });

    // Explanation if present
    if (q.explanation) {
      doc.setTextColor(100, 116, 139);
      doc.setFont('helvetica', 'italic');
      const explLines = doc.splitTextToSize(`Explanation: ${q.explanation}`, pageWidth - 44);
      doc.text(explLines, 22, y);
      y += explLines.length * 4.5;
      doc.setFont('helvetica', 'normal');
    }

    y += 4;
  });

  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`Page ${i} of ${totalPages} - Generated by Exam Portal`, pageWidth / 2, 290, { align: 'center' });
  }

  doc.save(`${studentName.replace(/[^a-zA-Z0-9]/g, '_')}_${exam.title.replace(/[^a-zA-Z0-9]/g, '_')}_Script.pdf`);
};

export const exportStudentSummaryPDF = (
  student: { name: string; email: string; college: string; mobile?: string },
  submissions: ExamSubmission[],
  exams: Exam[]
) => {
  const doc = new jsPDF('p', 'mm', 'a4');
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header Title
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, pageWidth, 32, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('EXAM PORTAL - STUDENT PERFORMANCE SUMMARY', 14, 12);

  doc.setFontSize(9.5);
  doc.setFont('helvetica', 'normal');
  doc.text(`Student: ${student.name} | College: ${student.college}`, 14, 19);
  doc.text(`Email: ${student.email} | Mobile: ${student.mobile || 'N/A'} | Total Exams Taken: ${submissions.length}`, 14, 25);

  let y = 40;

  // Table Header
  doc.setFillColor(241, 245, 249);
  doc.rect(14, y, pageWidth - 28, 8, 'F');
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'bold');

  doc.text('Date', 18, y + 5.5);
  doc.text('Exam Name', 45, y + 5.5);
  doc.text('Type', 110, y + 5.5);
  doc.text('Marks', 130, y + 5.5);
  doc.text('Score %', 150, y + 5.5);
  doc.text('Duration', 175, y + 5.5);

  y += 8;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);

  submissions.forEach((sub, idx) => {
    if (y > 275) {
      doc.addPage();
      y = 20;
    }

    const exam = exams.find(e => e.id === sub.examId);
    const examTitle = exam ? exam.title : 'Exam';
    const dateStr = new Date(sub.submittedAt).toLocaleDateString('en-GB');
    const minutes = Math.floor(sub.durationSeconds / 60);
    const seconds = sub.durationSeconds % 60;
    const durationFormatted = `${minutes}m ${seconds}s`;

    if (idx % 2 === 0) {
      doc.setFillColor(248, 250, 252);
      doc.rect(14, y, pageWidth - 28, 7, 'F');
    }
    doc.setDrawColor(226, 232, 240);
    doc.line(14, y + 7, pageWidth - 14, y + 7);

    doc.setTextColor(15, 23, 42);
    doc.text(dateStr, 18, y + 5);
    doc.text(doc.splitTextToSize(examTitle, 60)[0] || '', 45, y + 5);
    doc.text(sub.isLive ? 'Live Exam' : 'Practice', 110, y + 5);
    doc.text(`${sub.marksObtained}/${sub.totalMarks}`, 130, y + 5);
    doc.text(`${sub.percentage.toFixed(1)}%`, 150, y + 5);
    doc.text(durationFormatted, 175, y + 5);

    y += 7;
  });

  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`Page ${i} of ${totalPages} - Generated by Exam Portal`, pageWidth / 2, 290, { align: 'center' });
  }

  doc.save(`${student.name.replace(/[^a-zA-Z0-9]/g, '_')}_Exam_Summary.pdf`);
};
